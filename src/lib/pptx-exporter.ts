import pptxgen from 'pptxgenjs'
import type { Deck, Slide, ThemeConfig } from '@/types/deck'
import { MB_THEME, DELOITTE_THEME } from '@/types/deck'

export function exportDeckToPptx(deck: Deck): void {
  const theme = deck.meta.brand === 'deloitte' ? DELOITTE_THEME : MB_THEME
  const pptx = new pptxgen()

  pptx.author = deck.meta.author || 'DeckForge'
  pptx.title = deck.meta.title
  pptx.subject = 'Generated by DeckForge'

  pptx.defineSlideMaster({
    title: 'MB_DARK',
    background: { color: '0A0A0A' },
    objects: [
      { text: { text: '', options: { x: 0, y: 0, w: '100%', h: '100%', fill: { color: '0A0A0A' } } } },
    ],
  })

  pptx.defineSlideMaster({
    title: 'MB_LIGHT',
    background: { color: 'FFFFFF' },
  })

  deck.slides.forEach((slide) => {
    addSlide(pptx, slide, theme)
  })

  pptx.writeFile({ fileName: `${deck.meta.title.replace(/[^a-zA-Z0-9]/g, '-')}.pptx` })
}

function addSlide(pptx: pptxgen, slide: Slide, theme: ThemeConfig): void {
  const masterName = slide.theme === 'dark' ? 'MB_DARK' : 'MB_LIGHT'
  const pptSlide = pptx.addSlide({ masterName })

  const textColor = slide.theme === 'dark' ? 'FFFFFF' : '262626'
  const accentColor = theme.colors.primary.replace('#', '')

  let yPos = 1.0

  slide.components.forEach((comp) => {
    switch (comp.type) {
      case 'heading': {
        const fontSize = comp.props.level === 1 ? 36 : 28
        pptSlide.addText(comp.props.text as string, {
          x: 0.8,
          y: yPos,
          w: 8.4,
          h: 1.0,
          fontSize,
          fontFace: 'Arial',
          color: textColor,
          bold: false,
          align: 'center',
        })
        yPos += 1.2
        break
      }
      case 'text': {
        pptSlide.addText(comp.props.text as string, {
          x: 0.8,
          y: yPos,
          w: 8.4,
          h: 0.6,
          fontSize: 14,
          fontFace: 'Arial',
          color: '7D7D7D',
          align: 'center',
        })
        yPos += 0.8
        break
      }
      case 'list': {
        const items = comp.props.items as string[]
        const textItems = items.map((item) => ({
          text: item,
          options: {
            bullet: { type: 'bullet' as const, color: accentColor },
            fontSize: 14,
            color: textColor,
            breakLine: true,
          },
        }))
        pptSlide.addText(textItems, {
          x: 1.2,
          y: yPos,
          w: 7.6,
          h: items.length * 0.45 + 0.3,
          fontFace: 'Arial',
          valign: 'top',
        })
        yPos += items.length * 0.45 + 0.5
        break
      }
      case 'table': {
        const headers = comp.props.headers as string[]
        const rows = comp.props.rows as string[][]
        const tableData = [
          headers.map(h => ({ text: h, options: { bold: true, color: 'FFFFFF', fill: { color: 'FF9102' } } })),
          ...rows.map(row => row.map(cell => ({ text: cell })))
        ]
        pptSlide.addTable(tableData as pptxgen.TableRow[], {
          x: 0.8,
          y: yPos,
          w: 8.4,
          fontSize: 11,
          fontFace: 'Arial',
          color: textColor,
          border: { type: 'solid', pt: 0.5, color: '7D7D7D' },
          autoPage: true,
        })
        yPos += (rows.length + 1) * 0.4 + 0.5
        break
      }
      case 'image': {
        const src = comp.props.src as string
        if (src && src.startsWith('data:')) {
          pptSlide.addImage({
            data: src,
            x: 2.0,
            y: yPos,
            w: 6.0,
            h: 3.0,
          })
          yPos += 3.3
        }
        break
      }
    }
  })
}
